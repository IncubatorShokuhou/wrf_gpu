"""Generate factual feedback selectors; preserve flags after d=(...) clauses."""
from pathlib import Path
import hashlib,json,re,sys,pprint
root=Path("<USER_HOME>/src/wrf_pristine/WRF/Registry")
rows={}
sources={}
for name in ("Registry.EM_COMMON","registry.noahmp"):
    path=root/name
    sources[name]=hashlib.sha256(path.read_bytes()).hexdigest()
    text=re.sub(r"\\\s*\n"," ",path.read_text())
    for number,line in enumerate(text.splitlines(),1):
        parts=line.split(None,8)
        if len(parts)<9 or parts[0]!="state":continue
        flags=parts[7]
        plain=re.sub(r"=\([^)]*\)","",flags)
        if "u" not in plain:continue
        output=re.match(r'\s*"([^\"]+)"',parts[8])
        if not output:continue
        key=output.group(1).upper()
        if key.strip() in ("","-"):continue
        method=re.search(r"u=\(([^:),]+)",flags)
        method=method.group(1) if method else "copy_fcn"
        row=(method,"s" in plain,parts[6],parts[1])
        if key in rows and rows[key]!=row:
            raise ValueError((key,rows[key],row))
        rows[key]=row
out=Path(sys.argv[1])
out.write_text('"""WRF Registry feedback selectors (factual metadata, generated by gen_registry.py)."""\n'
    +'# Sources: '+json.dumps(sources,sort_keys=True)+'\n'
    +'# value: (operator, smooth, stagger, storage)\n'
    +'FEEDBACK_FIELDS = '+pprint.pformat(dict(sorted(rows.items())),width=100,sort_dicts=True)+'\n')
print(len(rows),"up fields incl explicit operators",sources)
