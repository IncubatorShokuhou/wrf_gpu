"""Build an isolated pristine-WRF arithmetic oracle; never edit the WRF tree.

Usage: JAX_PLATFORMS=cpu python build_oracle.py --output LANE/oracle
FC defaults to the staged conda compiler. All build files stay under --output.
The module's routines from SETUP_RAND_PERTURB onwards are copied verbatim.
Only domain/config type definitions and wrf_debug are stubbed, not arithmetic.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--wrf", type=Path, default=Path("<USER_HOME>/src/wrf_pristine/WRF"))
    parser.add_argument("--driver", type=Path, default=Path(__file__).with_name("oracle.f90"))
    parser.add_argument("--steps", type=int, default=4)
    args = parser.parse_args()
    dest = args.output.resolve()
    dest.mkdir(parents=True, exist_ok=False)
    source = args.wrf / "dyn_em/module_stoch.F"
    text = source.read_text()
    # Keep module declarations, then all original bodies except INITIALIZE_STOCH.
    head = text[:text.index("      SUBROUTINE INITIALIZE_STOCH")]
    body = text[text.index("      subroutine SETUP_RAND_PERTURB"):]
    (dest / "module_stoch.F90").write_text(head + body)
    (dest / "types.f90").write_text('''module module_configure
type grid_config_rec_type
integer :: start_year, start_month, start_day, start_hour, nens
end type
end module
module module_domain
type domain
integer :: num_tiles=1, num_stoch_levels=5
integer :: i_start(1),i_end(1),j_start(1),j_end(1)
real,allocatable :: rand_real(:,:,:),rand_imag(:,:,:)
end type
end module
subroutine wrf_debug(level,message)
integer :: level
character(*) :: message
print *, message
stop 9
end subroutine
subroutine wrf_message(message)
character(*) :: message
print *, message
end subroutine
subroutine wrf_error_fatal(message)
character(*) :: message
print *, message
stop 10
end subroutine
''')
    # Compile only the recursively needed original FFTPACK5 sources.
    fft_dir = args.wrf / "external/fftpack/fftpack5"
    files = {p.stem.lower(): p for p in fft_dir.glob("*.F")}
    selected, pending = {}, ["cfft1i", "cfft1b"]
    while pending:
        name = pending.pop()
        if name in selected:
            continue
        path = files[name]
        selected[name] = path
        calls = re.findall(r"\bcall\s+(\w+)", path.read_text(), flags=re.I)
        pending.extend(c.lower() for c in calls if c.lower() in files and c.lower() not in selected)
    for name, path in selected.items():
        (dest / f"{name}.f90").write_bytes(path.read_bytes())
    driver = args.driver.resolve()
    (dest / "oracle.f90").write_bytes(driver.read_bytes())
    fc = os.environ.get("FC", "<DATA_ROOT>/canairy_meteo/artifacts/envs/wrf-build/bin/gfortran")
    command = [fc, "-O2", "-ffp-contract=off", "-fcheck=bounds", "-fwrapv", "-fallow-argument-mismatch", "-ffree-line-length-none", "-cpp",
               "types.f90", "module_stoch.F90", *[f"{name}.f90" for name in selected], "oracle.f90", "-o", "oracle.exe"]
    with tempfile.TemporaryDirectory(prefix="compiler-tmp-", dir=dest) as tmp:
        subprocess.run(command, cwd=dest, env={**os.environ, "TMPDIR": tmp}, check=True, timeout=180)
    subprocess.run([str(dest / "oracle.exe")], cwd=dest, check=True, timeout=600)
    sources = [source, *selected.values(), driver]
    manifest = {"source": "pristine WRF dyn_em/module_stoch.F + original FFTPACK5",
                "scope": "standalone arithmetic; RNG generated by original gfortran intrinsic; not coupled qualification",
                "compiler": subprocess.check_output([fc, "--version"], text=True).splitlines()[0],
                "command": command, "shape_ijk": [18, 5, 16], "steps": args.steps,
                "seed": {"iseed": 811, "nens": 7, "start": "2026-10-13_18:00:00"},
                "tolerances": {"spectral_ar_atol": 2e-7, "spectral_ar_rtol": 3e-6,
                               "fft_atol": 2e-5, "fft_rtol": 4e-6,
                               "setup_rtol": 4e-6, "setup_absolute_policy": "16*REAL_epsilon*max(abs(reference))",
                               "tendencies_atol": 1e-6, "tendencies_rtol": 3e-6},
                "files": {str(p): hashlib.sha256(p.read_bytes()).hexdigest() for p in sources},
                "oracle_bin_sha256": hashlib.sha256((dest / "oracle.bin").read_bytes()).hexdigest()}
    (dest / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
