"""Execute the actual native column via CPU interpretation and original bounds.

This is a compiled-artifact numerical/resource check, never a GPU claim. The
enclosure is generated by build_controls.py BEFORE evaluating candidate values.
"""
import argparse
import json
from pathlib import Path
import resource
import sys
import time

import numpy as np
from build_controls import configurations


def main():
    ap=argparse.ArgumentParser();ap.add_argument('tree',type=Path);ap.add_argument('out',type=Path)
    ap.add_argument('--cases',default=','.join(map(str,range(1,25))));args=ap.parse_args()
    sys.path.insert(0,str(args.tree/'src'))
    import jax
    import jax.numpy as jnp
    from gpuwrf.kernels.phys_cammg import full_column,SURFACE_FIELDS
    assert jax.devices()[0].platform=='cpu'
    with np.load(args.tree/'proofs/s2_cammg/fixtures/convection.npz') as z:bank={k:z[k] for k in z.files}
    with np.load(args.tree/'proofs/s2_cammg/fixtures/compiled_enclosure.npz') as z:bounds={k:z[k] for k in z.files}
    groups={};values={};cases=list(map(int,args.cases.split(',')))
    for case in cases:
        cu,shcu,modes=configurations(case);groups.setdefault((cu,shcu),[]).append(case)
    receipt={'backend':'cpu','GPU_execution':False,'groups':[],'rows':[],'PASS':True}
    def save():
        receipt['maxrss_KiB']=resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
        args.out.write_text(json.dumps(receipt,indent=2)+'\n')
        np.savez_compressed(args.out.with_suffix('.npz'),**values)
    try:
        for (cu,shcu),selected in groups.items():
            def function(f,dt,it,am,ai,co):
                return full_column(f,dt,it,cu=cu,shcu=shcu,accum_mode=am,aitken_mode=ai,coarse_mode=co,interpret=True)
            case=selected[0];prefix=f'c{case:02d}_s1'
            sample={k.split('_input_',1)[1]:jnp.asarray(v).reshape((1,) if k.split('_input_',1)[1] in SURFACE_FIELDS else (1,25))
                    for k,v in bank.items() if k.startswith(prefix+'_input_')}
            _,_,modes=configurations(case);params=(sample,jnp.float32(18),jnp.int32(1),*map(jnp.float32,modes))
            begin=time.monotonic()
            compiled=jax.jit(function).lower(*params).compile()
            compile_s=time.monotonic()-begin;memory=compiled.memory_analysis()
            group={'cu':cu,'shcu':shcu,'compile_s':compile_s,
                   'argument_bytes':memory.argument_size_in_bytes,'output_bytes':memory.output_size_in_bytes,
                   'temporary_bytes':memory.temp_size_in_bytes};receipt['groups'].append(group);save()
            print('COMPILED',json.dumps(group),flush=True)
            for case in selected:
                _,_,modes=configurations(case)
                for step in (1,2):
                    prefix=f'c{case:02d}_s{step}'
                    fields={k.split('_input_',1)[1]:jnp.asarray(v).reshape((1,) if k.split('_input_',1)[1] in SURFACE_FIELDS else (1,25))
                            for k,v in bank.items() if k.startswith(prefix+'_input_')}
                    begin=time.monotonic();result,fatal=compiled(fields,jnp.float32(18),jnp.int32(step),*map(jnp.float32,modes))
                    jax.block_until_ready((result,fatal));elapsed=time.monotonic()-begin
                    assert np.asarray(fatal).shape==(1,) and np.all(np.asarray(fatal)==0),(case,step,'fatal')
                    row={'case':case,'step':step,'finite':True,'outside':0,'different':0,'seconds':elapsed,'fields':{}}
                    for name,array in result.items():
                        got=np.asarray(array).reshape(-1);ref=bank[prefix+'_output_'+name]
                        lo=bounds['lo_'+prefix+'_'+name];hi=bounds['hi_'+prefix+'_'+name]
                        assert got.shape==ref.shape==lo.shape==hi.shape and got.dtype==ref.dtype,(name,got.shape,ref.shape)
                        assert all(np.all(np.isfinite(a)) for a in (got,ref,lo,hi)),(case,step,name,'nonfinite')
                        assert np.all(lo<=hi),(name,'invalid enclosure')
                        outside=(got<lo)|(got>hi);different=got!=ref
                        count=int(np.count_nonzero(outside));row['outside']+=count;row['different']+=int(np.count_nonzero(different))
                        if count:row['fields'][name]={'outside':count,'first':np.argwhere(outside)[:8].tolist(),
                            'max_abs':float(np.max(np.abs(got.astype(np.float64)-ref))),
                            'max_excess':float(np.max(np.maximum(lo.astype(np.float64)-got,got.astype(np.float64)-hi)))}
                        values[prefix+'_'+name]=got
                    receipt['rows'].append(row);receipt['PASS']&=row['outside']==0;save()
                    print('ROW',json.dumps(row),flush=True)
            del compiled;jax.clear_caches()
    finally:save()
    print(json.dumps(receipt));assert receipt['PASS'],'native CPU artifact outside independent original enclosure'


if __name__=='__main__':main()
