"""Emit src/gpuwrf/physics/wrf_aer_opt3_tables.py from pristine WRF V4.7.1 sources (aer_opt=3 lookup tables).

usage: python scripts/extract_wrf_aer_opt3_tables.py [WRF_PHYS_DIR] [--check]

Parses the DATA statements of ``module_ra_aerosol.F`` (raod_lut / ssa_lut / asy_lut (type, band, RH),
lower_wvl / upper_wvl, rhs) and the ``lookup_tabl(RH, T, kind)`` assignments of ``gt_aod``
(module_radiation_driver.F) exactly as written (decimal literals kept as text, REAL by the consumer).
``--check`` compares against the committed module instead of writing it.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src/gpuwrf/physics/wrf_aer_opt3_tables.py"


def _joined(text: str) -> str:
    """Fortran free-form continuation joined; comments after '!' dropped."""

    lines = [ln.split("!", 1)[0].rstrip() for ln in text.splitlines()]
    out, buf = [], ""
    for ln in lines:
        if ln.endswith("&"):
            buf += ln[:-1] + " "
            continue
        out.append(buf + ln.lstrip("& ").rstrip() if buf else ln)
        buf = ""
    return "\n".join(out)


def _routine(text: str, name: str) -> str:
    m = re.search(rf"subroutine {name}\b(.*?)end subroutine {name}", text, re.S | re.I)
    assert m, name
    return _joined(m.group(1))


def _numbers(s: str) -> list[str]:
    return [t.strip() for t in s.split(",") if t.strip()]


def _lut(body: str, name: str) -> list[list[list[str]]]:
    lut = [[[None] * 8 for _ in range(14)] for _ in range(3)]
    for m in re.finditer(rf"data \({name}\((\d),ib,(\d)\),ib=1,N_BANDS\) /([^/]*)/", body, re.I):
        vals = _numbers(m.group(3))
        assert len(vals) == 14, (name, m.group(1), m.group(2), len(vals))
        for ib, v in enumerate(vals):
            lut[int(m.group(1)) - 1][ib][int(m.group(2)) - 1] = v
    assert all(v is not None for t in lut for b in t for v in b), name
    return lut


def extract(phys: Path) -> str:
    aer = (phys / "module_ra_aerosol.F").read_text()
    rad = (phys / "module_radiation_driver.F").read_text()
    main = _routine(aer, "calc_aerosol_rrtmg_sw")
    lower = _numbers(re.search(r"data \(lower_wvl\(i\),i=1,N_BANDS\) /([^/]*)/", main, re.I).group(1))
    upper = _numbers(re.search(r"data \(upper_wvl\(i\),i=1,N_BANDS\) /([^/]*)/", main, re.I).group(1))
    tables = {}
    rhs = None
    for routine, name in (("calc_spectral_aod_rrtmg_sw", "raod_lut"), ("calc_spectral_ssa_rrtmg_sw", "ssa_lut"),
                          ("calc_spectral_asy_rrtmg_sw", "asy_lut")):
        body = _routine(aer, routine)
        r = _numbers(re.search(r"data \(rhs\(i\),i=1,8\) /([^/]*)/", body, re.I).group(1))
        assert rhs in (None, r), routine
        rhs = r
        tables[name] = _lut(body, name)
    gt = _routine(rad, "gt_aod")
    look = [[[None] * 3 for _ in range(4)] for _ in range(8)]
    for m in re.finditer(r"lookup_tabl\((\d),(\d),(\d)\)\s*=\s*([0-9.E+-]+)", gt):
        look[int(m.group(1)) - 1][int(m.group(2)) - 1][int(m.group(3)) - 1] = m.group(4)
    assert all(v is not None for a in look for b in a for v in b)
    rh_arr = _numbers(re.search(r"rh_arr\s*=\s*\(/([^/]*)/\)", gt).group(1))
    assert len(lower) == len(upper) == 14 and len(rhs) == 8 and len(rh_arr) == 8

    def lit(x):
        if isinstance(x, list):
            return "(" + ", ".join(lit(v) for v in x) + ("," if len(x) == 1 else "") + ")"
        return x

    return f'''"""WRF V4.7.1 aer_opt=3 lookup tables (generated by scripts/extract_wrf_aer_opt3_tables.py; do not edit).

module_ra_aerosol.F calc_aerosol_rrtmg_sw / calc_spectral_{{aod,ssa,asy}}_rrtmg_sw (SF79 rural/urban/maritime,
index [type][band][rh]) and module_radiation_driver.F gt_aod (lookup_tabl [rh][t][water/ice/black-carbon]).
Decimal literals as in the Fortran DATA statements; consumers round them to REAL (float32).
"""

LOWER_WVL = {lit(lower)}
UPPER_WVL = {lit(upper)}
RHS = {lit(rhs)}
RAOD_LUT = {lit(tables["raod_lut"])}
SSA_LUT = {lit(tables["ssa_lut"])}
ASY_LUT = {lit(tables["asy_lut"])}
GT_AOD_RH = {lit(rh_arr)}
GT_AOD_LOOKUP = {lit(look)}
'''


def main(argv):
    phys = Path(next((a for a in argv if not a.startswith("--")), "<USER_HOME>/src/wrf_pristine/WRF/phys"))
    text = extract(phys)
    if "--check" in argv:
        same = OUT.read_text() == text
        print("MATCH" if same else "DIFFERS")
        return 0 if same else 1
    OUT.write_text(text)
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
