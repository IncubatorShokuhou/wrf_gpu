"""Literal Ferrier saturation adjustment, module_mp_fer_hires.F:2572–2746.

WRF uses REAL input/output and local temperature/vapor, but HIGH_PRES
COND/DEP, SSAT and (CONDENSE only) WCdum. These are intentional DOUBLE
islands; all other calculations stay REAL32. Tables are generated by the
unmodified WRF FPVSX/FPVSX0 routines, not a substitute saturation formula.
"""
from functools import lru_cache
from pathlib import Path

import jax
from jax import lax
import jax.numpy as jnp
import numpy as np

from gpuwrf._x64_config import configure_jax_x64

configure_jax_x64()

F = np.float32
CP, RD, RV = F(1004.6), F(287.04), F(461.5)
EPS = F(RD / RV)
XLV, XLF = F(2.5e6), F(3.3358e5)
XLS = F(XLV + XLF)
RCP = F(F(1) / CP)
RCPRV = F(RCP / RV)
XLV1, XLS1 = F(XLV / CP), F(XLS / CP)
XLV3, XLS3 = F(F(XLV * XLV) * RCPRV), F(F(XLS * XLS) * RCPRV)
EPSQ = F(1e-12)


@lru_cache(maxsize=1)
def host_tables():
    """Cache only host arrays: safe when first called inside a JIT trace (E206)."""
    with np.load(Path(__file__).with_name("tables.npz"), allow_pickle=False) as data:
        return {name: data[name].copy() for name in data.files}


def fpvs(t, *, water: bool):
    """WRF FPVS/FPVS0 in kPa, including its out-of-table fallbacks."""
    t = jnp.asarray(t, jnp.float32)
    table = jnp.asarray(host_tables()["tbpvs0" if water else "tbpvs"], jnp.float32)
    # GPVS computes 0.02 in REAL before these scale factors.
    xinc = F(F(330 - 180) / F(7500))
    c1 = F(F(1) - F(F(180) / xinc))
    c2 = F(F(1) / xinc)
    xj = jnp.minimum(jnp.maximum(c1 + c2 * t, F(1)), F(7501))
    j = jnp.minimum(xj, F(7500)).astype(jnp.int32)
    value = table[j - 1] + (xj - j.astype(jnp.float32)) * (table[j] - table[j - 1])
    liquid = F(.61078) * jnp.exp(F(17.2694) * (t - F(273.16)) / (t - F(35.86)))
    ice = F(.61078) * jnp.exp(F(21.8746) * (t - F(273.16)) / (t - F(7.66)))
    outside = liquid if water else jnp.where(t > F(330), liquid, ice)
    return jnp.where((t >= F(180)) & (t <= F(330)), value, outside)


def _ws(p, t, rh, water):
    es = jnp.minimum(F(1000) * fpvs(t, water=water), F(.99) * p)
    return rh * EPS * es / (p - es)


def _adjust(p, cloud, t, vapor, rh, *, water, active=None):
    p, cloud, t, vapor, rh = (jnp.asarray(x, jnp.float32) for x in (p, cloud, t, vapor, rh))
    ws = _ws(p, t, rh, water)
    dwv = vapor - ws
    initial_dwv = dwv
    zero = jnp.zeros_like(t)
    coeff1, coeff3 = (XLV1, XLV3) if water else (XLS1, XLS3)

    def body(carry):
        iteration, values = carry
        carry = values
        td, vd, wc, total, ws, dwv, done = carry
        # The RHS is entirely REAL before assignment to HIGH_PRES.
        cond = (dwv / (F(1) + coeff3 * ws / (td * td))).astype(jnp.float64)
        if water:
            cond = jnp.maximum(cond, -wc)
        new_t = (td.astype(jnp.float64) + jnp.float64(coeff1) * cond).astype(jnp.float32)
        new_v = (vd.astype(jnp.float64) - cond).astype(jnp.float32)
        new_wc = wc + cond if water else wc
        new_total = (total.astype(jnp.float64) + cond).astype(jnp.float32)
        new_ws = _ws(p, new_t, rh, water)
        new_dwv = new_v - new_ws
        # WRF's REAL ratio is widened on assignment to SSAT.
        ssat = (new_dwv / new_ws).astype(jnp.float64)
        # .001 is a REAL literal widened to HIGH_PRES in the PARAMETER.
        limit = jnp.float64(F(.001))
        negative_limit = jnp.float64(F(-.001))
        finished = (ssat >= negative_limit) & (ssat <= limit)
        if water:
            finished |= (ssat < negative_limit) & (new_wc <= jnp.float64(EPSQ))
        old = (td, vd, wc, total, ws, dwv)
        new = (new_t, new_v, new_wc, new_total, new_ws, new_dwv)
        values = (*tuple(jnp.where(done, a, b) for a, b in zip(old, new)), done | finished)
        return iteration + 1, values

    done = jnp.zeros_like(t, dtype=bool) if active is None else ~active
    values = (t, vapor, cloud.astype(jnp.float64), zero, ws, dwv, done)

    def condition(carry):
        iteration, values = carry
        # Integer MAX lowers in Triton; reduce_or does not. This reduction is
        # local to one column tile in the native kernel, never domain-wide.
        return (iteration < 10) & (jnp.max((~values[-1]).astype(jnp.int32)) > 0)

    _, values = lax.while_loop(condition, body, (jnp.int32(0), values))
    td, vd, wc, total, ws, dwv, done = values
    # WRF's nonconvergence fallback returns the initial deficit, preserving
    # the final dummy T/WV (DEPOSIT arguments have INTENT(INOUT)).
    return jnp.where(done, total, initial_dwv), td, vd


def condense(p, cloud, t, vapor, rh, *, active=None):
    """Total cloud condensation, kg/kg; dummy caller arguments are read-only."""
    return _adjust(p, cloud, t, vapor, rh, water=True, active=active)[0]


def deposit(p, t, vapor, rh, *, active=None):
    """Total ice deposition plus WRF's two INTENT(INOUT) dummy arguments."""
    return _adjust(p, jnp.zeros_like(t), t, vapor, rh, water=False, active=active)
