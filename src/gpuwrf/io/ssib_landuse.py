def ssib_landuse_initial(*,dataset,category,snowc,day,cen_lat):
    """module_physics_init.F:1838-1840,1955-1980, usemonalb=.false., XICE=0."""
    if dataset not in _TABLES: raise ValueError('SSiB unsupported LANDUSE vegetation map')
    if not np.isfinite(snowc).all() or not np.isfinite(cen_lat): raise ValueError('SSiB nonfinite LANDUSE input')
    table=np.asarray(_TABLES[dataset],np.float32)
    season=1 if day<105 or day>288 else 0
    if cen_lat<0:season=1-season
    if table.shape[0]==1:season=0
    index=np.asarray(category,np.int32)-1
    if np.any(index<0) or np.any(index>=table.shape[1]):
        raise ValueError('SSiB LANDUSE category outside pristine table')
    rows=table[season,index]
    albbck=rows[...,0]/np.float32(100)
    # SCFX has no season dimension: WRF READ retains its last season's values.
    scfx=table[-1,index,5]
    albedo=np.where(np.asarray(snowc)>np.float32(.5),albbck*(np.float32(1)+scfx),albbck)
    water=16 if dataset in ('USGS','SSIB') else 17
    return dict(albbck=albbck,albedo=albedo,emiss=rows[...,2],mavail=rows[...,1],
                znt=rows[...,3]/np.float32(100),
                xland=np.where(np.asarray(category)==water,np.float32(2),np.float32(1)))


def ssib_landuse_from_input(ds,run_dir):
    custom=Path(run_dir)/'LANDUSE.TBL'
    if custom.exists() and hashlib.sha256(custom.read_bytes()).hexdigest()!=LANDUSE_SHA256:
        raise ValueError('SSiB custom LANDUSE.TBL is not qualified; use the pristine table')
    if 'Times' not in ds.variables or not hasattr(ds,'CEN_LAT'):
        raise ValueError('SSiB requires Times/CEN_LAT for WRF LANDUSE seasonal initialization')
    raw=np.asarray(ds['Times'][0]).astype('S1')
    start=datetime.strptime(b''.join(raw.tolist()).decode().strip('\x00 '),'%Y-%m-%d_%H:%M:%S')
    name='LU_INDEX' if 'LU_INDEX' in ds.variables else 'IVGTYP'
    lu=np.floor(np.asarray(ds[name][0],np.float32)+np.float32(.5)).astype(np.int32)
    dataset=str(ds.MMINLU).strip();water=16 if dataset in ('USGS','SSIB') else 17
    lu=np.where(lu==0,water,lu)
    snowc=np.asarray(ds['SNOWC'][0],np.float32) if 'SNOWC' in ds.variables else np.float32(0)
    return ssib_landuse_initial(dataset=dataset,category=lu,snowc=snowc,
                               day=start.timetuple().tm_yday,cen_lat=float(ds.CEN_LAT))
