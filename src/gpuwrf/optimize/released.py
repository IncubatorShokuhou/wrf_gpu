"""Physics configurations released for `gpuwrf optimize` (exact FINAL D6 PASS tuples; no JAX).

The shipped list ``released_v0.4.0.json`` is generated by proofs/w41_optimize/build_released.py
from the v0.4.0 FINAL release checkpoint. A configuration is the exact seven-option tuple per
domain for one domain count. Single options are never released on their own: an option paired
with other options it was not measured with is a new, unvalidated combination.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

PHYSICS = ("mp_physics", "bl_pbl_physics", "sf_sfclay_physics", "sf_surface_physics",
           "ra_lw_physics", "ra_sw_physics", "cu_physics")
SCHEMA = "gpuwrf.optimize.released.v1"
RELEASED_PATH = Path(__file__).with_name("released_v0.4.0.json")
E41_LEVELS = ("any", "PASS")
# Run window and geometry: never a physics/dynamics choice, so never "context".
WINDOW_GROUPS = ("time_control", "domains")


def config_id(physics):
    """Stable ID of a per-domain physics mapping (same as optimize candidate IDs)."""
    return "p-"+hashlib.sha256(json.dumps(physics, sort_keys=True).encode()).hexdigest()[:12]


tuple_id = config_id


def settings(config, max_dom):
    """Non-window namelist settings, absent physics/dynamics keys resolved to WRF Registry defaults.

    Per-domain values are cut to ``max_dom`` (a scalar applies to every domain). Used only to
    disclose where a study case differs from the run that qualified a configuration.
    """
    from gpuwrf.io.wrf_registry_defaults import WRF_REGISTRY_DEFAULTS

    out = {}
    for group, values in config.items():
        if group in WINDOW_GROUPS:
            continue
        for key, value in values.items():
            if key not in PHYSICS:
                out[f"{group}.{key}"] = _domains(value, max_dom)
    for key, (group, entries, _kind, default) in WRF_REGISTRY_DEFAULTS.items():
        name = f"{group}.{key}"
        if key not in PHYSICS and name not in out and default is not None:
            out[name] = _domains([default]*max_dom if entries == "max_domains" else default, max_dom)
    return out


def _domains(value, max_dom):
    if isinstance(value, list):
        values = value[:max_dom] if len(value) >= max_dom else value+[value[-1]]*(max_dom-len(value))
        return values[0] if len(set(map(json.dumps, values))) == 1 else values
    return value


def load(path=RELEASED_PATH):
    from gpuwrf import __version__

    data = json.loads(Path(path).read_text())
    if data.get("schema") != SCHEMA or tuple(data.get("physics_keys", ())) != PHYSICS:
        raise ValueError("unsupported optimize release list")
    release = str(data.get("release", ""))
    # The list binds the release's validated programs: same major.minor only.
    if not release.startswith("v") or ".".join(__version__.split(".")[:2]) != ".".join(release[1:].split(".")[:2]):
        raise ValueError(f"optimize release list {release} does not apply to gpuwrf {__version__}")
    entries = {}
    for entry in data["configurations"]:
        if config_id(entry["physics"]) != entry["id"] or any(len(v) != entry["max_dom"] for v in entry["physics"].values()):
            raise ValueError(f"corrupt release entry {entry.get('id')}")
        if not entry["qualified_by"] or any(r["D6"] != "PASS" for r in entry["qualified_by"]):
            raise ValueError(f"release entry {entry['id']} lacks D6 PASS evidence")
        entries[entry["id"]] = entry
    data["by_id"] = entries
    data["by_run"] = {r["run"]: entry for entry in entries.values() for r in entry["qualified_by"]}
    return data


def describe(physics):
    return ", ".join(f"{k}={'/'.join(map(str, v))}" for k, v in physics.items())


def resolve(data, physics, max_dom, *, e41="any"):
    """Return the release entry of an exact configuration or raise (refuse everything else)."""
    if e41 not in E41_LEVELS:
        raise ValueError(f"e41 must be one of {E41_LEVELS}")
    key = config_id(physics)
    entry = data["by_id"].get(key)
    if entry is None or entry["max_dom"] != max_dom:
        raise ValueError(f"{key} ({describe(physics)}, max_dom={max_dom}) is not released for gpuwrf optimize "
                         f"in {data['release']}: no FINAL D6 PASS run used this exact combination; "
                         "see `gpuwrf optimize released`")
    if e41 == "PASS" and entry["best_E41"] != "PASS":
        raise ValueError(f"{key} ({describe(physics)}) has no E41 PASS qualifying run (best {entry['best_E41']}); "
                         "the study requires e41=PASS")
    return entry


def lookup(data, name):
    """A study names a configuration by release ID (p-...) or qualifying run (c00, F20-WN3-0227)."""
    entry = data["by_id"].get(name) or data["by_run"].get(name)
    if entry is None:
        raise ValueError(f"unknown released configuration {name!r}; see `gpuwrf optimize released`")
    return entry


def run_settings(data, run):
    merged = dict(data["base_settings"])
    for key, value in run["context_vs_c00"].items():
        if value is None:
            merged.pop(key, None)
        else:
            merged[key] = value
    return merged


def context_differences(data, entry, case_config, max_dom):
    """Settings in which the study case differs from the closest qualifying run (disclosure only)."""
    case = settings(case_config, max_dom)
    best = None
    for run in entry["qualified_by"]:  # preferred order; the closest context wins
        reference = run_settings(data, run)
        keys = sorted(k for k in set(reference) | set(case) if reference.get(k) != case.get(k))
        if best is None or len(keys) < len(best[1]):
            best = (run, keys, reference)
    run, keys, reference = best
    return {"run": run["run"], "geography": run["geography"], "E41": run["E41"],
            "differences": {k: {"case": case.get(k), "qualified_run": reference.get(k)} for k in keys}}


def table(data, *, max_dom=None, e41="any"):
    rows = []
    for entry in data["configurations"]:
        if (max_dom is not None and entry["max_dom"] != max_dom) or (e41 == "PASS" and entry["best_E41"] != "PASS"):
            continue
        runs = ",".join(f"{r['run']}({r['E41']})" for r in entry["qualified_by"])
        rows.append(f"{entry['id']}  max_dom={entry['max_dom']}  {describe(entry['physics'])}  E41={entry['best_E41']}  runs={runs}")
    return rows
